"""Bake the hero title's glyph outlines into title-glyphs.js.

Run after changing the hero <h1> copy (requires `pip install fonttools`):
  python3 tools/bake-title-glyphs.py "Don’t let me distract you, keep scrolling."
Each contour becomes a flat list of cubic segments in font units:
  [x0, y0, c1x, c1y, c2x, c2y, x, y, ...]
"""
import json, pathlib, sys
from fontTools.pens.basePen import BasePen
from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parent.parent

class CubicPen(BasePen):
    def __init__(self, glyphset):
        super().__init__(glyphset); self.contours = []; self.cur = None
    def _moveTo(self, p):
        self.cur = [round(p[0]), round(p[1])]; self.contours.append(self.cur)
    def _lineTo(self, p):
        (x0, y0), (x1, y1) = self._getCurrentPoint(), p
        self.cur += [round(x0 + (x1 - x0) / 3), round(y0 + (y1 - y0) / 3),
                     round(x0 + (x1 - x0) * 2 / 3), round(y0 + (y1 - y0) * 2 / 3), round(x1), round(y1)]
    def _curveToOne(self, a, b, p):
        self.cur += [round(v) for v in (*a, *b, *p)]
    def _qCurveToOne(self, q, p):
        x0, y0 = self._getCurrentPoint()
        self.cur += [round(x0 + 2 / 3 * (q[0] - x0)), round(y0 + 2 / 3 * (q[1] - y0)),
                     round(p[0] + 2 / 3 * (q[0] - p[0])), round(p[1] + 2 / 3 * (q[1] - p[1])), round(p[0]), round(p[1])]
    def _closePath(self):
        x0, y0 = self.cur[0], self.cur[1]
        if self.cur[-2:] != [x0, y0]: self._lineTo((x0, y0))
    _endPath = _closePath

font = TTFont(ROOT / 'fonts/font-4.ttf')  # Bricolage Grotesque ExtraBold
cmap, glyphset = font.getBestCmap(), font.getGlyphSet()
glyphs = {}
for ch in sorted(set(sys.argv[1]) - {' '}):
    pen = CubicPen(glyphset); glyphset[cmap[ord(ch)]].draw(pen)
    glyphs[ch] = pen.contours
data = {'unitsPerEm': font['head'].unitsPerEm, 'ascender': font['OS/2'].sTypoAscender, 'glyphs': glyphs}
(ROOT / 'title-glyphs.js').write_text(
    '// Generated by tools/bake-title-glyphs.py from Bricolage Grotesque ExtraBold (OFL).\n'
    'window.TITLE_GLYPHS=' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n')
print(f"baked {len(glyphs)} glyphs")
